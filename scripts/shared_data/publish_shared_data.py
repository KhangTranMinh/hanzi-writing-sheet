#!/usr/bin/env python3
"""Copy the shared source data to the web and mobile application bundles."""
import json
import re
import shutil
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'shared' / 'data'
WEB = ROOT / 'web'
MOBILE = ROOT / 'react-native'


def replace_data(destination):
    # Prepare the entire replacement before touching the existing data directory.
    with tempfile.TemporaryDirectory(prefix='.shared-data-', dir=destination.parent) as temp:
        temp_path = Path(temp)
        staged = temp_path / 'data'
        backup = temp_path / 'previous'
        shutil.copytree(SOURCE, staged)
        if destination.exists():
            destination.rename(backup)
        try:
            staged.rename(destination)
        except OSError:
            if backup.exists():
                backup.rename(destination)
            raise


practice = json.loads((SOURCE / 'practice' / 'data.json').read_text(encoding='utf-8'))
assert isinstance(practice, list), 'Practice data must be an array'
lessons_dir = SOURCE / 'lessons'
# The 0000-0000 file is an authoring template, not a published lesson.
lesson_ids = sorted(path.stem for path in lessons_dir.glob('*.json')
                    if re.fullmatch(r'\d{4}-\d{4}', path.stem) and path.stem != '0000-0000')
for lesson_id in lesson_ids:
    lesson = json.loads((lessons_dir / f'{lesson_id}.json').read_text(encoding='utf-8'))
    if not isinstance(lesson.get('title'), str) or not lesson['title'].strip() or not isinstance(lesson.get('items'), list):
        raise ValueError(f'Invalid lesson: {lesson_id}')
    if any(not isinstance(item.get(key), str) or not item[key].strip() for item in lesson['items'] for key in ('hanzi', 'pinyin', 'meaning')):
        raise ValueError(f'Invalid card in lesson: {lesson_id}')
replace_data(WEB / 'data')
replace_data(MOBILE / 'data')
(WEB / 'lessons' / 'index.json').write_text(json.dumps(lesson_ids, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
characters = sorted(path.stem for path in (SOURCE / 'worksheet').glob('*.json'))
lines = ['// Generated by scripts/shared_data/publish_shared_data.py. Do not edit.', "import type { CharacterData } from './worksheet-generator';", '', 'export const bundledData: Record<string, CharacterData> = {']
lines += [f'  {json.dumps(char, ensure_ascii=False)}: require({json.dumps("../data/worksheet/" + char + ".json", ensure_ascii=False)}),' for char in characters]
lines += ['};', '']
(MOBILE / 'lib' / 'worksheet-data.ts').write_text('\n'.join(lines), encoding='utf-8')
lines = ['// Generated by scripts/shared_data/publish_shared_data.py. Do not edit.', 'export type LessonItem = { hanzi: string; pinyin: string; meaning: string };', 'export type Lesson = { title: string; items: LessonItem[] };', 'export const lessons: Record<string, Lesson> = {']
lines += [f'  {json.dumps(id)}: require("../data/lessons/{id}.json"),' for id in lesson_ids]
lines += ['};', '']
(MOBILE / 'lib' / 'lessons-data.ts').write_text('\n'.join(lines), encoding='utf-8')
print(f'Synced {len(characters)} characters, {len(lesson_ids)} lessons and {len(practice)} practice cards.')
